#!/usr/bin/env python3
"""Generate slang input and the typed bridge for the data-driven Flutter UI.

Canonical text lives only in packages/presentation/locales. Run with --generate
from the repository root after resolving the pinned Flutter packages.
"""
from __future__ import annotations
import argparse
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
APP = ROOT / 'apps/mobile'

def identifier(key: str) -> str:
    words = re.split(r'[^a-zA-Z0-9]+', key)
    return words[0] + ''.join(w[:1].upper() + w[1:] for w in words[1:])

def dart(value: str) -> str:
    return json.dumps(value, ensure_ascii=True).replace('$', r'\$')

def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--generate', action='store_true')
    args = parser.parse_args()
    english = json.loads((ROOT / 'packages/presentation/locales/en-US.json').read_text())
    chinese = json.loads((ROOT / 'packages/presentation/locales/zh-CN.json').read_text())
    if english.keys() != chinese.keys():
        raise SystemExit('Locale keys differ.')
    keys = {key: identifier(key) for key in english}
    if len(set(keys.values())) != len(keys):
        raise SystemExit('Generated identifiers collide.')
    stage = APP / '.dart_tool/homeverb_i18n'
    stage.mkdir(parents=True, exist_ok=True)
    for locale, catalog in [('en-US', english), ('zh-CN', chinese)]:
        for key, value in catalog.items():
            if set(re.findall(r'\{([a-zA-Z]+)\}', value)) != set(re.findall(r'\{([a-zA-Z]+)\}', english[key])):
                raise SystemExit(f'Placeholder mismatch: {key}')
        (stage / f'{locale}.json').write_text(json.dumps({keys[k]: v for k, v in catalog.items()}, ensure_ascii=True, indent=2) + '\n')
    # Each source is a legacy presentation token, never a translated command ID.
    # Parameters are explicit and are never guessed by matching rendered strings.
    sources = {value: key for key, value in english.items()}
    lines = ["// Generated by scripts/generate_flutter_i18n.py. Do not edit.",
             "import 'strings.g.dart';", '',
             'String? translateSource(Translations t, String source, Map<String, Object> args) => switch (source) {']
    for source, key in sources.items():
        params = sorted(set(re.findall(r'\{([a-zA-Z]+)\}', source)))
        call = 't.' + keys[key]
        if params:
            call = 't.' + keys[key] + '(' + ', '.join(f'{p}: args[{dart(p)}] ?? {dart("{" + p + "}")}' for p in params) + ')'
        lines.append(f'  {dart(source)} => {call},')
    lines.extend(['  _ => null,', '};', '',
                  'String translateError(Translations t, String code) => switch (code) {'])
    for key in english:
        if key.startswith('error.') and key != 'error.generic':
            lines.append(f'  {dart(key[6:])} => t.{keys[key]},')
    lines.extend(['  _ => t.errorGeneric(code: code),', '};', ''])
    lines.append('String? sourceForKey(String key) => switch (key) {')
    for key, value in english.items():
        lines.append(f'  {dart(key)} => {dart(value)},')
    lines.extend(['  _ => null,', '};', ''])
    (APP / 'lib/gen').mkdir(exist_ok=True)
    (APP / 'lib/gen/source_messages.g.dart').write_text('\n'.join(lines))
    # Retain the existing shared English asset for the approval contract fixture.
    (APP / 'assets/en-US.json').write_bytes((ROOT / 'packages/presentation/locales/en-US.json').read_bytes())
    if args.generate:
        subprocess.run(['fvm', 'dart', 'run', 'slang'], cwd=APP, check=True)
        for path in (APP / 'lib/gen').glob('strings*.dart'):
            source = path.read_text()
            source = ''.join(c if ord(c) < 128 else (f'\\u{ord(c):04x}' if ord(c) <= 0xffff else f'\\u{{{ord(c):x}}}') for c in source)
            path.write_text(source)
        subprocess.run(['fvm', 'dart', 'format', 'lib/gen/source_messages.g.dart'], cwd=APP, check=True)
    print(f'Prepared {len(english)} shared messages for en-US and zh-CN.')

if __name__ == '__main__':
    main()
